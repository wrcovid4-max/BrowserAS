/** Server-side research tools. They use NO cookies or sign-ins and refuse private-network targets, so they can't touch your accounts or devices. */
object WebFetch {
    private const val UA = "Mozilla/5.0 (compatible; HydrogenResearch/0.3)"
    private fun strip(h: String) = h.replace(Regex("(?is)<(script|style|noscript|nav|footer|header|svg|form|aside)[^>]*>.*?</\\1>"), " ").replace(Regex("(?s)<[^>]+>"), " ")
        .replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"").replace("&#39;", "'").replace("&nbsp;", " ").replace(Regex("\\s+"), " ").trim()

    fun parseSearch(html: String): List<SearchResult> {
        val links = Regex("""<a[^>]*class="result__a"[^>]*href="([^"]+)"[^>]*>(.*?)</a>""", RegexOption.DOT_MATCHES_ALL).findAll(html).toList()
        val snippets = Regex("""<a[^>]*class="result__snippet"[^>]*>(.*?)</a>""", RegexOption.DOT_MATCHES_ALL).findAll(html).map { strip(it.groupValues[1]) }.toList()
        return links.mapIndexedNotNull { i, m ->
            var u = m.groupValues[1].replace("&amp;", "&")
            if (u.contains("uddg=")) u = URLDecoder.decode(u.substringAfter("uddg=").substringBefore('&'), "UTF-8")
            if (u.startsWith("//")) u = "https:$u"
            if (!u.startsWith("http")) null else SearchResult(strip(m.groupValues[2]), u, snippets.getOrElse(i) { "" })
        }.take(8)
    }

    fun search(query: String): List<SearchResult> {
        val c = URL("https://html.duckduckgo.com/html/?q=" + URLEncoder.encode(query, "UTF-8")).openConnection() as HttpURLConnection
        c.setRequestProperty("User-Agent", UA); c.connectTimeout = 10_000; c.readTimeout = 15_000
        try { if (c.responseCode != 200) error("Search returned HTTP ${c.responseCode} (the search provider may be blocking automated requests)"); return parseSearch(c.inputStream.bufferedReader().readText()) } finally { c.disconnect() }
    }

    fun fetch(url: String, maxChars: Int = 12_000, depth: Int = 0): FetchedPage {
        Ssrf.check(url)?.let { error(it) }
        val c = URL(url).openConnection() as HttpURLConnection
        c.instanceFollowRedirects = false; c.setRequestProperty("User-Agent", UA); c.connectTimeout = 10_000; c.readTimeout = 15_000
        try {
            var code = c.responseCode
            if (code in 301..308) { val loc = c.getHeaderField("Location") ?: error("Redirect without target"); val next = java.net.URI(url).resolve(loc).toString(); if (depth >= 5) error("Too many redirects"); Ssrf.check(next)?.let { error("Redirect blocked: $it") }; return fetch(next, maxChars, depth + 1) }
            if (code != 200) error("HTTP $code")
            val type = c.contentType.orEmpty()
            if (!type.contains("text/") && !type.contains("xml") && !type.contains("json")) error("Not a text page ($type)")
            val html = c.inputStream.use { it.readNBytes(1_500_000) }.toString(Charsets.UTF_8)
            val title = Regex("(?is)<title[^>]*>(.*?)</title>").find(html)?.groupValues?.get(1)?.let(::strip).orEmpty()
            return FetchedPage(url, title.ifBlank { url }, strip(html).take(maxChars))
        } finally { c.disconnect() }
    }
}

object ReportBuilder {
    fun markdown(j: JobRecord): String = buildString {
        val d = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US)
        appendLine("# ${j.goal.take(120)}"); appendLine()
        appendLine("*${j.agentName} · ${d.format(Date(j.startedAt))} · ${j.state}*"); appendLine()
        appendLine(j.result.trim()); appendLine()
        if (j.sources.isNotEmpty()) { appendLine("## Sources"); j.sources.forEach { appendLine("${it.n}. [${it.title.ifBlank { it.url }}](${it.url}) — retrieved ${d.format(Date(it.fetchedAt))}") }; appendLine() }
        appendLine("## What the agent did"); j.steps.filter { it.kind in setOf("tool", "approval", "blocked", "warning", "verify") }.forEach { appendLine("- ${it.title}${if (it.approval.isNotBlank()) " (${it.approval})" else ""}") }
        appendLine(); appendLine("*Generated by an AI agent. Check important claims against the sources above.*")
    }
}

object MemoryRules {
    fun sensitiveReason(text: String): String? = when {
        Redactor.redact(text) != text -> "it contains a card number, password, one-time code or key"
        Regex("""(?i)\b(ssn|social security|passport|national id|cnic)\b""").containsMatchIn(text) -> "it looks like a government ID"
        else -> null
    }
    fun search(items: List<MemoryItem>, query: String, project: String?, limit: Int = 8): List<MemoryItem> {
        val q = query.lowercase().split(Regex("\\W+")).filter { it.length > 2 }.toSet()
        return items.filter { it.approved && (it.scope == "long" || it.scope == "session" || project.isNullOrBlank() || it.project == project) }
            .map { m -> m to q.count { m.text.lowercase().contains(it) } }.filter { it.second > 0 }.sortedByDescending { it.second }.take(limit).map { it.first }
    }
    fun purge(items: List<MemoryItem>, retentionDays: Int, now: Long): List<MemoryItem> =
        if (retentionDays <= 0) items else items.filter { it.scope == "session" || now - it.createdAt < retentionDays * 86_400_000L }
}
